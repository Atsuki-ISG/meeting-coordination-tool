-- 017: bookings にゲスト用カレンダーイベントの ID を保存する
--
-- 予約作成時には 2 つの Google カレンダーイベントを作る:
--   (1) ゲスト＋主催者を招待する Meet 付きイベント（guest_event_id）
--   (2) チーム内部用イベント（google_event_id、従来から保存済み）
-- これまで (1) の ID を永続化していなかったため、キャンセル時に (2) しか削除できず、
-- ゲスト側のカレンダーに Meet 付きイベントが残り続け、主催者の空き時間も塞がれていた。
-- このカラムを追加し、キャンセル時に両方のイベントを削除できるようにする。
--
-- 既存の予約レコードは guest_event_id が NULL のままになるため、キャンセル処理側は
-- NULL をスキップする（従来どおり内部用イベントのみ削除）。

ALTER TABLE bookings ADD COLUMN IF NOT EXISTS guest_event_id TEXT;
